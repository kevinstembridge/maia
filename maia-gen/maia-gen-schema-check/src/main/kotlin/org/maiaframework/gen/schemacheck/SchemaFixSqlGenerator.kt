package org.maiaframework.gen.schemacheck

import org.maiaframework.gen.schema.ExpectedColumnDef
import org.maiaframework.gen.schema.ExpectedCompositeForeignKeyDef
import org.maiaframework.gen.schema.ExpectedForeignKeyDef
import org.maiaframework.gen.schema.ExpectedIndexDef

/**
 * Renders a [SchemaDiffReport] as a draft SQL script that would bring the actual database
 * schema back in line with the spec. This is a starting point for a human to review, not
 * something to run unattended:
 *
 * - Additive fixes (add column, add FK, create index, drop-then-recreate a mismatched PK) are
 *   emitted as live statements.
 * - A missing-column/nullable-tightening fix that could fail against existing data (adding a
 *   NOT NULL column, or setting NOT NULL on one) is emitted commented-out behind a back-fill
 *   TODO, since the correct back-fill value is something only the spec author knows.
 * - Anything destructive that corrects a mere WARNING (an extra table/column/foreign
 *   key/index not in the spec) is emitted commented-out, since the extra item may be
 *   intentional and the tool has no way to tell.
 * - A wholly MISSING table isn't reconstructed here — that's what the generator's own
 *   create-table SQL script (maia.sqlCreateScriptsDir) is for.
 */
object SchemaFixSqlGenerator {

    fun generate(report: SchemaDiffReport): String {

        val lines = mutableListOf(
            "-- Generated by maia-gen-schema-check",
            "-- Review every statement before running it against a real database.",
            "-- Statements are not wrapped in a transaction; wrap them yourself for all-or-nothing.",
        )

        val tablesWithFixes = report.tables.filter { it.hasErrors || it.hasWarnings }.sortedBy { it.schemaAndTableName }

        if (tablesWithFixes.isEmpty()) {
            lines.add("")
            lines.add("-- No drift found -- nothing to fix.")
            return lines.joinToString("\n")
        }

        tablesWithFixes.forEach { table ->
            lines.add("")
            lines.add("-- ${table.schemaAndTableName} [${table.status}]")
            lines.addAll(fixesFor(table))
        }

        return lines.joinToString("\n")

    }

    private fun fixesFor(table: TableDiff): List<String> {

        if (table.status == TableStatus.MISSING) {
            return listOf(
                "-- Table is missing entirely -- regenerate it via the module's create-table SQL",
                "-- script (see maia.sqlCreateScriptsDir) rather than a hand-written fix here.",
            )
        }

        val statements = mutableListOf<String>()

        table.missingColumns.forEach { statements.addAll(addColumnStatements(table.schemaAndTableName, it)) }
        table.mismatchedColumns.forEach { statements.addAll(fixColumnStatements(table.schemaAndTableName, it)) }
        table.primaryKeyMismatch?.let { statements.addAll(fixPrimaryKeyStatements(table.schemaAndTableName, it)) }
        table.missingForeignKeys.forEach { statements.add(addForeignKeyStatement(table.schemaAndTableName, it)) }
        table.missingCompositeForeignKeys.forEach { statements.add(addCompositeForeignKeyStatement(table.schemaAndTableName, it)) }
        table.missingIndexes.forEach { statements.add(createIndexStatement(table.schemaAndTableName, it)) }

        if (table.status == TableStatus.EXTRA) {
            statements.add("-- WARNING: table exists in the database but not in the spec. Review before dropping:")
            statements.add("-- DROP TABLE ${table.schemaAndTableName};")
        }

        table.extraColumns.forEach { statements.addAll(dropExtraColumnStatements(table.schemaAndTableName, it)) }
        table.extraForeignKeys.forEach { statements.addAll(extraForeignKeyNote(table.schemaAndTableName, it)) }
        table.extraIndexes.forEach { statements.addAll(dropExtraIndexStatements(it)) }

        return statements

    }

    private fun addColumnStatements(schemaAndTableName: String, column: ExpectedColumnDef): List<String> {

        val addStatement = "ALTER TABLE $schemaAndTableName ADD COLUMN ${column.name} ${column.postgresType};"

        return if (column.nullable) {
            listOf(addStatement)
        } else {
            listOf(
                addStatement,
                "-- TODO: back-fill '${column.name}' on existing rows, then:",
                "-- ALTER TABLE $schemaAndTableName ALTER COLUMN ${column.name} SET NOT NULL;",
            )
        }

    }

    private fun fixColumnStatements(schemaAndTableName: String, mismatch: ColumnMismatch): List<String> {

        val statements = mutableListOf<String>()

        if (mismatch.expectedType != mismatch.actualType) {
            statements.add(
                "ALTER TABLE $schemaAndTableName ALTER COLUMN ${mismatch.name} TYPE ${mismatch.expectedType} " +
                        "USING ${mismatch.name}::${mismatch.expectedType};"
            )
        }

        if (mismatch.expectedNullable != mismatch.actualNullable) {
            if (mismatch.expectedNullable) {
                statements.add("ALTER TABLE $schemaAndTableName ALTER COLUMN ${mismatch.name} DROP NOT NULL;")
            } else {
                statements.add("-- TODO: back-fill '${mismatch.name}' on existing rows, then:")
                statements.add("-- ALTER TABLE $schemaAndTableName ALTER COLUMN ${mismatch.name} SET NOT NULL;")
            }
        }

        return statements

    }

    private fun fixPrimaryKeyStatements(schemaAndTableName: String, mismatch: PrimaryKeyMismatch): List<String> {

        val constraintName = mismatch.actualConstraintName ?: "${bareTableName(schemaAndTableName)}_pkey"

        return listOf(
            "ALTER TABLE $schemaAndTableName DROP CONSTRAINT IF EXISTS $constraintName;",
            "ALTER TABLE $schemaAndTableName ADD PRIMARY KEY (${mismatch.expected.joinToString(", ")});",
        )

    }

    private fun addForeignKeyStatement(schemaAndTableName: String, foreignKey: ExpectedForeignKeyDef): String {

        val constraintName = "${bareTableName(schemaAndTableName)}_${foreignKey.columnName}_fkey"

        return "ALTER TABLE $schemaAndTableName ADD CONSTRAINT $constraintName FOREIGN KEY (${foreignKey.columnName}) " +
                "REFERENCES ${foreignKey.referencedSchemaAndTable}(${foreignKey.referencedColumn});"

    }

    private fun addCompositeForeignKeyStatement(schemaAndTableName: String, foreignKey: ExpectedCompositeForeignKeyDef): String {

        // Must match CreateTableSqlRenderer's composite FK constraint naming exactly, or generated
        // fix-SQL would create a constraint whose name the generator itself would never recognize.
        val constraintName = "${bareTableName(schemaAndTableName)}_${foreignKey.columnNames.first()}_fkey"
        val localColumns = foreignKey.columnNames.joinToString(", ")
        val referencedColumns = foreignKey.referencedColumns.joinToString(", ")

        return "ALTER TABLE $schemaAndTableName ADD CONSTRAINT $constraintName FOREIGN KEY ($localColumns) " +
                "REFERENCES ${foreignKey.referencedSchemaAndTable}($referencedColumns);"

    }

    private fun createIndexStatement(schemaAndTableName: String, index: ExpectedIndexDef): String {

        val unique = if (index.unique) "UNIQUE " else ""
        return "CREATE ${unique}INDEX ${index.name} ON $schemaAndTableName (${index.columns.joinToString(", ")});"

    }

    private fun dropExtraColumnStatements(schemaAndTableName: String, columnName: String): List<String> {

        return listOf(
            "-- WARNING: extra column '$columnName' not in spec. Review before dropping:",
            "-- ALTER TABLE $schemaAndTableName DROP COLUMN $columnName;",
        )

    }

    private fun extraForeignKeyNote(schemaAndTableName: String, columnName: String): List<String> {

        return listOf(
            "-- WARNING: extra foreign key on column '$columnName' not in spec. Find its constraint name" +
                    " (e.g. \\d $schemaAndTableName) and drop it manually if it's no longer wanted.",
        )

    }

    private fun dropExtraIndexStatements(indexName: String): List<String> {

        return listOf(
            "-- WARNING: extra index '$indexName' not in spec. Review before dropping:",
            "-- DROP INDEX $indexName;",
        )

    }

    private fun bareTableName(schemaAndTableName: String): String = schemaAndTableName.substringAfter(".")

}
